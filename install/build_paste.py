#!/usr/bin/env python3
"""Generate install/agent-paste.md from SKILL.md + the script contracts.

    python install/build_paste.py            # write agent-paste.md
    python install/build_paste.py --check    # exit 3 if the paste file is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "install" / "agent-paste.md"

CONTRACTS = """
## Paste-mode contracts

Every command prints one JSON object on stdout with `--json`; logs go to stderr.
Envelope: `status, stage, output, artifacts, checks, next, error, device,
duration_ms`. Exit codes: `0` ok, `2` warn, `3` failed check, `4` needs user
input, `5` missing capability, `6` invalid input.

Errors carry `kind, detail, fix, doc, retryable`. Quote `fix` verbatim.

## Paste-mode rules

- Run `python install/doctor.py --json` first; report missing capabilities with
  their fix instead of guessing.
- Ask at most 8 intake questions, pre-filled from `probe.py --quick`.
- Never claim a gate passed: run `scripts/check.py`.
- Never use paid APIs, cloud rendering, telemetry or watermarks.
- State lives in `edit/state.json`; resume with `forge.py resume`.
"""


def build() -> str:
    skill = (ROOT / "SKILL.md").read_text(encoding="utf-8")
    head = ("<!-- generated by install/build_paste.py — do not edit by hand -->\n"
            "# video-vfx-editor (single-file paste skill)\n\n"
            "Paste this whole file into a skills UI that accepts one text document.\n"
            "It is the complete operating contract; the repository adds the scripts.\n\n")
    scripts = sorted(p.name for p in (ROOT / "scripts").glob("*.py"))
    listing = "\n## Scripts in this skill\n\n" + "\n".join(f"- `scripts/{s}`" for s in scripts) + "\n"
    return head + skill + CONTRACTS + listing


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Build the single-file paste skill")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != text:
            print("install/agent-paste.md is stale — run python install/build_paste.py", file=sys.stderr)
            return 3
        print("agent-paste.md is current")
        return 0
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    lines = text.count("\n") + 1
    print(f"wrote {TARGET} ({lines} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
